    CONSTRAINT uk_holidays_business_date UNIQUE (business_id, holiday_date),
    CONSTRAINT fk_holidays_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE TABLE queue_policies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    emergency_weight integer NOT NULL,
    appointment_weight integer NOT NULL,
    priority_weight integer NOT NULL,
    normal_weight integer NOT NULL,
    aging_points_per_minute double precision NOT NULL,
    max_wait_minutes integer NOT NULL,
    fairness_every_n integer NOT NULL,
    emergency_bypasses_fairness boolean NOT NULL,
    appointment_policy varchar(32) NOT NULL,
    appointment_early_window_minutes integer NOT NULL,
    appointment_late_grace_minutes integer NOT NULL,
    no_show_grace_minutes integer NOT NULL,
