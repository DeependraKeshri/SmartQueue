);
CREATE INDEX idx_audit_business_created ON audit_logs (business_id, created_at);
CREATE INDEX idx_audit_business_action ON audit_logs (business_id, action);

-- Audit logs are append-only: block UPDATE and DELETE at the database level.
CREATE FUNCTION audit_logs_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_logs is append-only';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_audit_logs_immutable BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION audit_logs_immutable();

