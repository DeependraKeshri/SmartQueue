-- SmartQueue initial schema (PostgreSQL). Must stay in sync with JPA entities (ddl-auto=validate).

CREATE TABLE businesses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    name varchar(120) NOT NULL,
    slug varchar(100) NOT NULL,
    public_id uuid NOT NULL,
    description varchar(500),
    logo_url varchar(500),
    timezone varchar(64) NOT NULL,
    token_prefix varchar(5) NOT NULL,
    active boolean NOT NULL,
    display_mode varchar(32) NOT NULL,
    allow_guest_join boolean NOT NULL,
    show_wait_on_display boolean NOT NULL,
    in_app_notifications_enabled boolean NOT NULL,
    email_notifications_enabled boolean NOT NULL,
    push_notifications_enabled boolean NOT NULL,
    auto_confirm_appointments boolean NOT NULL,
    contact_email varchar(190),
    contact_phone varchar(30),
    CONSTRAINT uk_businesses_slug UNIQUE (slug),
    CONSTRAINT uk_businesses_public_id UNIQUE (public_id)
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    email varchar(190) NOT NULL,
    password_hash varchar(100) NOT NULL,
    full_name varchar(120) NOT NULL,
    phone varchar(30),
    role varchar(32) NOT NULL,
    business_id bigint,
    active boolean NOT NULL,
    failed_login_attempts integer NOT NULL,
    locked_until timestamptz,
    last_login_at timestamptz,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);
CREATE INDEX idx_users_business ON users (business_id);
CREATE INDEX idx_users_role ON users (role);

CREATE TABLE services (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    public_id uuid NOT NULL,
    name varchar(120) NOT NULL,
    description varchar(500),
    estimated_duration_minutes integer NOT NULL,
    active boolean NOT NULL,
    queue_enabled boolean NOT NULL,
    appointments_enabled boolean NOT NULL,
    priority_allowed boolean NOT NULL,
    slot_interval_minutes integer NOT NULL,
    max_advance_booking_days integer NOT NULL,
    min_lead_minutes integer NOT NULL,
    token_prefix varchar(5),
    deleted boolean NOT NULL,
    CONSTRAINT uk_services_public_id UNIQUE (public_id),
    CONSTRAINT fk_services_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);
CREATE INDEX idx_services_business ON services (business_id, deleted);

CREATE TABLE counters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    name varchar(80) NOT NULL,
    active boolean NOT NULL,
    status varchar(16) NOT NULL,
    assigned_staff_id bigint,
    CONSTRAINT uk_counters_business_name UNIQUE (business_id, name),
    CONSTRAINT fk_counters_business FOREIGN KEY (business_id) REFERENCES businesses (id),
    CONSTRAINT fk_counters_staff FOREIGN KEY (assigned_staff_id) REFERENCES users (id)
);
CREATE INDEX idx_counters_business ON counters (business_id);
CREATE INDEX idx_counters_staff ON counters (assigned_staff_id);

CREATE TABLE staff_services (
    user_id bigint NOT NULL,
    service_id bigint NOT NULL,
    PRIMARY KEY (user_id, service_id),
    FOREIGN KEY (user_id) REFERENCES users (id),
    FOREIGN KEY (service_id) REFERENCES services (id)
);

CREATE TABLE counter_services (
    counter_id bigint NOT NULL,
    service_id bigint NOT NULL,
    PRIMARY KEY (counter_id, service_id),
    FOREIGN KEY (counter_id) REFERENCES counters (id),
    FOREIGN KEY (service_id) REFERENCES services (id)
);

CREATE TABLE business_hours (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    day_of_week varchar(12) NOT NULL,
    open_time time,
    close_time time,
    closed boolean NOT NULL,
    CONSTRAINT uk_hours_business_day UNIQUE (business_id, day_of_week),
    CONSTRAINT fk_hours_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);

CREATE TABLE break_periods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    day_of_week varchar(12),
    start_time time NOT NULL,
    end_time time NOT NULL,
    label varchar(80),
    CONSTRAINT fk_breaks_business FOREIGN KEY (business_id) REFERENCES businesses (id)
);
CREATE INDEX idx_breaks_business ON break_periods (business_id);

CREATE TABLE holidays (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    holiday_date date NOT NULL,
