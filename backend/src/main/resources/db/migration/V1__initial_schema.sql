CREATE INDEX idx_queues_business ON queues (business_id);

CREATE TABLE appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    service_id bigint NOT NULL,
    customer_id bigint NOT NULL,
    start_at timestamptz NOT NULL,
    end_at timestamptz NOT NULL,
    status varchar(16) NOT NULL,
    idempotency_key varchar(64),
    notes varchar(500),
    reschedule_count integer NOT NULL,
    cancelled_at timestamptz,
    cancel_reason varchar(255),
    CONSTRAINT uk_appointments_idem UNIQUE (customer_id, idempotency_key),
    CONSTRAINT fk_appointments_business FOREIGN KEY (business_id) REFERENCES businesses (id),
    CONSTRAINT fk_appointments_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT fk_appointments_customer FOREIGN KEY (customer_id) REFERENCES users (id)
