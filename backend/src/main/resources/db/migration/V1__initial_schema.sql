    max_recalls integer NOT NULL,
    approaching_threshold integer NOT NULL,
    CONSTRAINT uk_policies_business UNIQUE (business_id),
    CONSTRAINT fk_policies_business FOREIGN KEY (business_id) REFERENCES businesses (id)
