CREATE TABLE queues (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    business_id bigint NOT NULL,
    service_id bigint NOT NULL,
    public_id uuid NOT NULL,
    name varchar(120) NOT NULL,
    status varchar(16) NOT NULL,
    token_prefix varchar(5) NOT NULL,
    last_token_number integer NOT NULL,
    sequence_date date,
    consecutive_high_priority_served integer NOT NULL,
    CONSTRAINT uk_queues_public_id UNIQUE (public_id),
    CONSTRAINT uk_queues_service UNIQUE (service_id),
    CONSTRAINT uk_queues_business_prefix UNIQUE (business_id, token_prefix),
    CONSTRAINT fk_queues_business FOREIGN KEY (business_id) REFERENCES businesses (id),
    CONSTRAINT fk_queues_service FOREIGN KEY (service_id) REFERENCES services (id)
