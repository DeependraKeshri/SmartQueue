CREATE INDEX idx_appointments_customer ON appointments (customer_id);

CREATE TABLE queue_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, row_version bigint NOT NULL DEFAULT 0,
    queue_id bigint NOT NULL,
    business_id bigint NOT NULL,
    service_id bigint NOT NULL,
    customer_id bigint,
    guest_name varchar(120),
    guest_phone varchar(30),
    public_id uuid NOT NULL,
    token_number integer NOT NULL,
    token_label varchar(16) NOT NULL,
    sequence_date date NOT NULL,
    status varchar(16) NOT NULL,
    source varchar(16) NOT NULL,
    priority varchar(16) NOT NULL,
    appointment_id bigint,
    counter_id bigint,
    served_by_id bigint,
    joined_at timestamptz NOT NULL,
    queue_time timestamptz NOT NULL,
    called_at timestamptz,
    serving_started_at timestamptz,
    completed_at timestamptz,
    cancelled_at timestamptz,
    no_show_at timestamptz,
    skipped_at timestamptz,
    recall_count integer NOT NULL,
    skip_count integer NOT NULL,
    approaching_notified_at timestamptz,
    no_show_warned_at timestamptz,
    idempotency_key varchar(64),
    note varchar(255),
    CONSTRAINT uk_entries_public_id UNIQUE (public_id),
    CONSTRAINT uk_entries_token UNIQUE (queue_id, sequence_date, token_number),
    CONSTRAINT uk_entries_idem UNIQUE (queue_id, idempotency_key),
    CONSTRAINT fk_entries_queue FOREIGN KEY (queue_id) REFERENCES queues (id),
    CONSTRAINT fk_entries_business FOREIGN KEY (business_id) REFERENCES businesses (id),
    CONSTRAINT fk_entries_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT fk_entries_customer FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_entries_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id),
    CONSTRAINT fk_entries_counter FOREIGN KEY (counter_id) REFERENCES counters (id),
    CONSTRAINT fk_entries_served_by FOREIGN KEY (served_by_id) REFERENCES users (id)
);
CREATE INDEX idx_entries_queue_status ON queue_entries (queue_id, status);
CREATE INDEX idx_entries_business_joined ON queue_entries (business_id, joined_at);
CREATE INDEX idx_entries_customer ON queue_entries (customer_id);
